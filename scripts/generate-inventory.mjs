#!/usr/bin/env node

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const repositoryRoot = resolve(import.meta.dirname, '..');
const outputPath = join(repositoryRoot, 'docs/baseline/inventory.json');

function filesUnder(relativeDirectory, extension) {
  const root = join(repositoryRoot, relativeDirectory);
  if (!existsSync(root)) return [];

  const visit = (directory) => readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) return visit(absolute);
    return !extension || entry.name.endsWith(extension) ? [absolute] : [];
  });

  return visit(root).map((absolute) => relative(repositoryRoot, absolute)).sort();
}

function routeInventory() {
  const routeFiles = filesUnder('packages/server/src/routes', '.ts');
  const routePattern = /app\.(get|post|put|patch|delete|options|head)\(\s*(['"])([^'"\n]+)\2/g;
  return routeFiles.flatMap((file) => {
    const source = readFileSync(join(repositoryRoot, file), 'utf8');
    return [...source.matchAll(routePattern)].map((match) => ({
      file,
      method: match[1].toUpperCase(),
      path: match[3],
    }));
  });
}

function frontendRoutes() {
  return filesUnder('frontend/src/app', 'page.tsx').map((file) => {
    const route = file
      .replace(/^frontend\/src\/app/, '')
      .replace(/\/page\.tsx$/, '')
      .replace(/\/\[\.\.\.([^/]+)\]/g, '/:$1*')
      .replace(/\/\[([^/]+)\]/g, '/:$1') || '/';
    return { file, route };
  });
}

function cliCommands() {
  const source = readFileSync(join(repositoryRoot, 'packages/cli/src/index.ts'), 'utf8');
  const usage = source.match(/Commands:\n([\s\S]*?)\n\nEnv:/)?.[1] ?? '';
  return usage
    .split('\n')
    .map((line) => line.trim().split(/\s{2,}/)[0])
    .filter(Boolean);
}

function sdkMethods() {
  const source = readFileSync(join(repositoryRoot, 'packages/sdk/src/index.ts'), 'utf8');
  return [...source.matchAll(/^  ([a-zA-Z][a-zA-Z0-9]*)\([^\n]*\):/gm)].map((match) => match[1]);
}

const inventory = {
  sourceOfTruth: 'Generated by scripts/generate-inventory.mjs',
  packages: [
    'packages/shared',
    'packages/server',
    'packages/sdk',
    'packages/cli',
    'frontend',
    'site',
  ],
  routes: routeInventory(),
  applicationServices: filesUnder('packages/server/src/application', '.ts'),
  repositories: filesUnder('packages/server/src/repos', '.ts'),
  migrations: filesUnder('packages/shared/db/migrations', '.sql'),
  frontendRoutes: frontendRoutes(),
  cliCommands: cliCommands(),
  sdkMethods: sdkMethods(),
  providerAndAgentModules: [
    ...filesUnder('packages/server/src/llm', '.ts'),
    ...filesUnder('packages/server/src/agents', '.ts'),
  ],
  schedulersAndJobs: [
    ...filesUnder('packages/server/src/scheduler', '.ts'),
    ...filesUnder('packages/server/src/jobs', '.ts'),
  ],
};

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(inventory, null, 2)}\n`);
console.log(`Wrote ${relative(repositoryRoot, outputPath)}`);
